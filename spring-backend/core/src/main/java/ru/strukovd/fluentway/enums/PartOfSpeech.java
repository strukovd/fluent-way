package ru.strukovd.fluentway.enums;

public enum PartOfSpeech {
	NOUN,             // существительное
	VERB,             // глагол
	ADJECTIVE,        // прилагательное
	ADVERB,           // наречие
	PRONOUN,          // местоимение
	PREPOSITION,      // предлог
	CONJUNCTION,      // союз
	INTERJECTION,     // междометие
	ARTICLE,          // артикль
	NUMERAL,          // числительное
	PARTICLE,         // частица
	DETERMINER,       // определитель (например: this, that)
	MODAL_VERB,       // модальный глагол (can, must и т.п.)
	PHRASE,           // фраза (если нужно описывать устойчивые выражения)
	OTHER             // для редких или не классифицированных случаев
}